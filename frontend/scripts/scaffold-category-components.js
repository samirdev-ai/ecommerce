#!/usr/bin/env node
/**
 * Category page — components scaffold (extend-only, idempotent).
 * Creates the 20 components under features/category/components/**.
 * Patches nothing existing. Creates only.
 *
 * Run: node scripts/scaffold-category-components.cjs
 */

import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const SRC = path.join(ROOT, "src");
const MANIFEST_PATH = path.join(ROOT, ".scaffold-manifest.json");

const manifest = fs.existsSync(MANIFEST_PATH)
  ? JSON.parse(fs.readFileSync(MANIFEST_PATH, "utf8"))
  : { version: 1, patches: {} };

const counters = { created: 0, skipped: 0 };

function saveManifest() {
  fs.writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2));
}

function createIfMissing(relPath, lines) {
  const full = path.join(SRC, relPath);
  if (fs.existsSync(full)) {
    counters.skipped++;
    console.log(`  \x1b[33m•\x1b[0m src/${relPath}  (exists)`);
    return;
  }
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, lines.join("\n") + "\n");
  counters.created++;
  console.log(`  \x1b[32m+\x1b[0m src/${relPath}`);
}

